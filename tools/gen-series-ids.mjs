#!/usr/bin/env node
/**
 * gen-series-ids — the series id set as a plain module the CLIENT bundle can import.
 *
 * `components/marks.tsx` cannot import `lib/data`: `OverviewBoard` is a client component and pulls
 * this file into the browser bundle, and `lib/data` reads `node:fs`.
 *
 * **Hyphenless ids are excluded.** `remittances` and `crar` are an ordinary word and an ordinary
 * acronym; linking every occurrence would assert a citation nobody made, and a false link is worse
 * than a missing one. **Emitted longest first**, because ids are strict prefixes of one another —
 * the `P-10` against `P-100` defect in another shape.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'lib', 'series-ids.generated.ts');

const ids = [];
const dir = join(ROOT, 'data', 'series');
for (const f of readdirSync(dir)) {
  if (!f.endsWith('.json')) continue;
  for (const r of JSON.parse(readFileSync(join(dir, f), 'utf8'))) if (r?.id) ids.push(r.id);
}
const linkable = ids.filter((id) => id.includes('-')).sort((a, b) => b.length - a.length || a.localeCompare(b));
const prefixCount = ids.filter((a) => ids.some((b) => b !== a && b.startsWith(`${a}-`))).length;
const excluded = ids.filter((id) => !id.includes('-')).sort();

writeFileSync(
  OUT,
  `// GENERATED by tools/gen-series-ids.mjs — do not edit. Regenerate with \`npm run series-ids\`.\n` +
    `// Longest first: ${prefixCount} ids are a strict prefix of another.\n` +
    `// Excluded (no hyphen, ordinary words): ${excluded.join(', ')}.\n` +
    `export const LINKABLE_SERIES_IDS: readonly string[] = ${JSON.stringify(linkable, null, 0).replace(/","/g, '", "')};\n`,
);
console.log(`gen-series-ids OK — ${linkable.length} linkable, ${excluded.length} excluded (${excluded.join(', ')}), ${prefixCount} prefix pair(s)`);
