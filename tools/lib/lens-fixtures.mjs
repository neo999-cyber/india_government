/**
 * Regenerate the lens-coverage fixtures from the live schemas, and stamp what they were built from.
 *
 * THE HAZARD THIS CLOSES. Both lens fixtures are derived from the domain and lens enums. When
 * `china` and `neighbourhood` were admitted, `lens-coverage-empty` began failing on `[lens]` — no
 * page built for the new values — instead of on `[lens-empty]`, the branch it exists to pin. Exit
 * code 1 either way. Selftest green. The branch went unchecked for two cycles, and it was found by
 * accident while doing something else.
 *
 * Branch assertions in the selftest turn that from a silent pass into a failure, which is necessary
 * and not sufficient: they say the fixture is wrong, not what to do, and the remedy was a line in a
 * state document asking the next author to remember. **A discipline requirement is what M2 and
 * build-freshness exist to replace.** So each fixture now carries GENERATED-FROM.json recording the
 * enums it was built against, the selftest fails if that no longer matches the live schemas, and the
 * failure names this script as the fix.
 *
 * The stamp is the mechanism, not the regeneration. A fixture regenerated by hand without running
 * this would carry a stale stamp and fail — which is correct, because the stamp is the claim.
 *
 * THIS MODULE HAS NO SIDE EFFECTS, and that is load-bearing rather than tidiness. The first
 * version put `liveEnums` in the runner, so the selftest's `import` executed the regeneration and
 * the fixtures were rebuilt every time the selftest ran — silently healing the exact drift the
 * stamp check exists to detect, and reporting green. A checker that repairs what it is checking is
 * asking the defect to report itself. The runner is tools/regen-lens-fixtures.mjs; this file only
 * defines.
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const schema = (n) => JSON.parse(readFileSync(join(ROOT, 'schemas', `${n}.schema.json`), 'utf8'));

export const liveEnums = () => ({
  domains: schema('ledger').properties.domains.items.enum,
  lenses: schema('series').properties.lenses.items.enum,
});

const LINK = '<a href="/series/fixture-series/">Fixture series</a>';

export function build(name, { lensesOnSeries, missingLens }) {
  const { domains, lenses } = liveEnums();
  const fx = join(ROOT, 'tests', 'fixtures', name);
  rmSync(fx, { recursive: true, force: true });

  mkdirSync(join(fx, 'data', 'series'), { recursive: true });
  const series = {
    id: 'fixture-series',
    title: 'Fixture series, not a real record',
    unit: 'count',
    domain: 'foreign',
    ...(lensesOnSeries ? { lenses: [...lenses] } : {}),
    tier: 'T1',
    source: { name: 'Fixture, not a real source', url: 'https://example.org/' },
    calendar: 'FY',
    points: [{ country: 'IND', period: 'FY2013-14', value: 1, status: 'verified' }],
  };
  writeFileSync(join(fx, 'data', 'series', 'one.json'), `${JSON.stringify([series], null, 2)}\n`);

  mkdirSync(join(fx, 'out', 'domains'), { recursive: true });
  writeFileSync(
    join(fx, 'out', 'domains', 'index.html'),
    `<!doctype html><html><body>\n<h1>Domains</h1>\n${domains.map((d) => `  <a href="/domains/${d}/">${d}</a>`).join('\n')}\n</body></html>\n`,
  );
  for (const d of domains) {
    mkdirSync(join(fx, 'out', 'domains', d), { recursive: true });
    const body = d === 'foreign' || (lensesOnSeries && lenses.includes(d)) ? LINK : '';
    writeFileSync(join(fx, 'out', 'domains', d, 'index.html'), `<!doctype html><html><body>\n<h1>${d}</h1>\n${body}\n</body></html>\n`);
  }

  mkdirSync(join(fx, 'out', 'lenses'), { recursive: true });
  writeFileSync(
    join(fx, 'out', 'lenses', 'index.html'),
    `<!doctype html><html><body>\n<h1>Lenses</h1>\n${lenses.map((l) => `  <a href="/lenses/${l}/">${l}</a>`).join('\n')}\n</body></html>\n`,
  );
  for (const l of lenses) {
    if (l === missingLens) continue;
    mkdirSync(join(fx, 'out', 'lenses', l), { recursive: true });
    const body = lensesOnSeries ? LINK : '<p>No series is read under this lens.</p>';
    writeFileSync(join(fx, 'out', 'lenses', l, 'index.html'), `<!doctype html><html><body>\n<h1>${l}</h1>\n${body}\n</body></html>\n`);
  }

  writeFileSync(
    join(fx, 'GENERATED-FROM.json'),
    `${JSON.stringify(
      {
        note:
          'Written by tools/regen-lens-fixtures.mjs. The selftest compares these enums against the ' +
          'live schemas and FAILS if they differ, because a fixture generated from a stale enum tests ' +
          'the wrong branch while still exiting 1. Do not hand-edit: re-run the script.',
        domains,
        lenses,
        ...(missingLens ? { missingLens } : {}),
      },
      null,
      2,
    )}\n`,
  );
  return { name, domains: domains.length, lenses: lenses.length };
}
