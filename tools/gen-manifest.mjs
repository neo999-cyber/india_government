#!/usr/bin/env node
/**
 * Generate the corpus manifest: one line per record, so orientation does not require scanning /data.
 *
 * WHY. `/data` is 2.3 MB across 645 records. Answering "what does the instrument already hold on X"
 * meant reading JSON files, and a phase that skips that step duplicates or contradicts a record that
 * already exists — the reason every phase begins with a scope note about collisions. A manifest of
 * id, title, domain and lenses answers it in a few hundred lines.
 *
 * GENERATED, NEVER HAND-MAINTAINED, and wired into `npm run build` so it cannot drift. A
 * hand-kept index of a corpus that gains records every cycle is a stale index within one cycle, and
 * a stale index is worse than none: it is read with the same confidence as a fresh one. Same call as
 * the fixture enum stamps.
 *
 * It is written to `docs/corpus-manifest.md` and committed, so it can be read at session start
 * without running anything.
 *
 * Usage:  node tools/gen-manifest.mjs   ·   npm run manifest
 */
import {readdirSync, readFileSync, writeFileSync, existsSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(ROOT, 'data');
const OUT = join(ROOT, 'docs', 'corpus-manifest.md');

function jsonFiles(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.') || e.name === 'incoming') continue;
    const full = join(dir, e.name);
    if (e.isDirectory()) out.push(...jsonFiles(full));
    else if (e.isFile() && e.name.endsWith('.json')) out.push(full);
  }
  return out;
}

/** One line per record. Title is truncated because this is an index, not a reader. */
const line = (r, extra) => {
  const lenses = (r.lenses ?? []).length ? ` {${(r.lenses ?? []).join(' ')}}` : '';
  const title = (r.title ?? r.whatChanged ?? r.framing ?? '').replace(/\s+/g, ' ').slice(0, 110);
  return `${r.id} · ${extra}${lenses} · ${title}`;
};

const layers = { series: [], ledger: [], provenance: [], pairs: [] };
for (const f of jsonFiles(DATA)) {
  const parsed = JSON.parse(readFileSync(f, 'utf8'));
  const list = Array.isArray(parsed) ? parsed : (parsed.records ?? parsed.series ?? []);
  const rel = f.replace(`${ROOT}/`, '');
  const layer = rel.includes('/series') ? 'series'
    : rel.includes('/ledger') ? 'ledger'
    : rel.includes('provenance') ? 'provenance'
    : rel.includes('pairs') ? 'pairs' : null;
  if (!layer) continue;
  for (const r of list) if (r && r.id) layers[layer].push({ r, rel });
}

const sections = [];
sections.push('# Corpus manifest');
sections.push('');
sections.push('**Generated by `tools/gen-manifest.mjs`, run as part of `npm run build`. Do not edit.**');
sections.push('');
sections.push('One line per record so orientation does not require scanning `/data`. Format:');
sections.push('`id · domain(s) {lenses} · title`. For the authoritative text, read the record.');
sections.push('');

const total = Object.values(layers).reduce((n, l) => n + l.length, 0);
sections.push(`${total} records — ${layers.ledger.length} ledger, ${layers.series.length} series, ` +
  `${layers.provenance.length} provenance, ${layers.pairs.length} pairs.`);
sections.push('');

for (const [name, items] of Object.entries(layers)) {
  if (!items.length) continue;
  sections.push(`## ${name} (${items.length})`);
  sections.push('');
  sections.push('```');
  const byFile = new Map();
  for (const it of items) {
    if (!byFile.has(it.rel)) byFile.set(it.rel, []);
    byFile.get(it.rel).push(it.r);
  }
  for (const [rel, recs] of [...byFile].sort()) {
    sections.push(`# ${rel}`);
    for (const r of recs) {
      const extra = name === 'ledger' ? (r.domains ?? []).join('+')
        : name === 'provenance' ? (r.affectsDomains ?? []).join('+')
        : (r.domain ?? '');
      sections.push(line(r, extra));
    }
  }
  sections.push('```');
  sections.push('');
}

const body = `${sections.join('\n')}`;
const prev = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
writeFileSync(OUT, body);
const bytes = Buffer.byteLength(body);
console.log(
  `manifest OK — ${total} records, ${bytes.toLocaleString()} bytes` +
    (prev === body ? ' (unchanged)' : prev === null ? ' (created)' : ' (updated)'),
);
